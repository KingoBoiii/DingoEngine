#!/bin/sh
# Usage: gather-notices.sh [--check] [output.md]
#
# Writes THIRD-PARTY-NOTICES.md (by default at the repository root) from scripts/notices/components.txt:
# a table of every third-party component a game ships with, then each one's licence text. The
# release jobs copy the file into every archive. --check writes nothing and fails when the file
# is out of date, so CI can catch a vendor bump that forgot to regenerate it.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
manifest="$root/scripts/notices/components.txt"
check=0
if [ "${1:-}" = "--check" ]; then
	check=1
	shift
fi
out=${1:-"$root/THIRD-PARTY-NOTICES.md"}

# The licence a component's file holds, or, for file@marker, the comment around the marker from
# that line to the comment's end.
licence_text() {
	file=${1%%@*}
	[ -f "$root/$file" ] || { echo "gather-notices: missing $file" >&2; exit 1; }
	if [ "$file" = "$1" ]; then
		cat "$root/$file"
	else
		awk -v marker="${1#*@}" 'index($0, marker) { on = 1 } on && /\*\// { exit } on' "$root/$file"
	fi
}

field() {
	echo "$1" | cut -d'|' -f"$2" | sed 's/^ *//; s/ *$//'
}

generate() {
	echo "# Third-party notices"
	echo
	echo "DingoEngine and the games built with it include the following third-party software. Each"
	echo "component's licence follows the table. Generated by \`scripts/gather-notices.sh\`; edit"
	echo "\`scripts/notices/components.txt\`, not this file."
	echo
	echo "| Component | Licence | Used for |"
	echo "|---|---|---|"
	grep -v '^#' "$manifest" | grep -v '^ *$' | while IFS= read -r line; do
		echo "| [$(field "$line" 1)]($(field "$line" 2)) | $(field "$line" 3) | $(field "$line" 4) |"
	done
	grep -v '^#' "$manifest" | grep -v '^ *$' | while IFS= read -r line; do
		echo
		echo "## $(field "$line" 1)"
		echo
		echo "$(field "$line" 2)"
		echo
		echo '```text'
		# sed adds the newline a file without a final one lacks, which would glue the fence to it.
		licence_text "$(field "$line" 5)" | tr -d '\r' | sed 's/[[:space:]]*$//; $a\\'
		echo '```'
	done
}

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
generate > "$tmp"

if [ "$check" = 1 ]; then
	if ! cmp -s "$tmp" "$out"; then
		echo "gather-notices: $out is out of date; run scripts/gather-notices.sh" >&2
		exit 1
	fi
	exit 0
fi
cp "$tmp" "$out"
echo "gather-notices: wrote $out"
