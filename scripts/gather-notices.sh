#!/bin/sh
# Usage: gather-notices.sh [--check] [output.md]
#
# Writes THIRD-PARTY-NOTICES.md (by default at the repository root) from scripts/notices/components.txt:
# a table of every third-party component a game ships with, then each one's licence text. The
# release jobs copy the file into every archive. --check writes nothing and fails when the file
# is out of date, so CI can catch a vendor bump that forgot to regenerate it.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
manifest="$root/scripts/notices/components.txt"
check=0
if [ "${1:-}" = "--check" ]; then
	check=1
	shift
fi
out=${1:-"$root/THIRD-PARTY-NOTICES.md"}

# The licence a component's file holds, or, for file@marker, the comment around the marker from
# that line to the comment's end. Fails when the file is missing or the marker matches nothing.
licence_text() {
	file=${1%%@*}
	[ -f "$root/$file" ] || { echo "gather-notices: missing $file" >&2; return 1; }
	if [ "$file" = "$1" ]; then
		cat "$root/$file"
	else
		awk -v marker="${1#*@}" 'index($0, marker) { on = 1 } on && /\*\// { exit } on; END { exit !on }' "$root/$file" ||
			{ echo "gather-notices: no '${1#*@}' in $file" >&2; return 1; }
	fi
}

field() {
	echo "$1" | cut -d'|' -f"$2" | sed 's/^ *//; s/ *$//'
}

# Windows checkouts may give the manifest CRLF endings.
components=$(mktemp)
tmp=$(mktemp)
trap 'rm -f "$components" "$tmp"' EXIT
grep -v '^#' "$manifest" | tr -d '\r' | grep -v '^ *$' > "$components"

# Checked here, outside any pipeline, since a failure inside one would not stop the script.
while IFS= read -r line; do
	licence_text "$(field "$line" 5)" > /dev/null
done < "$components"

generate() {
	echo "# Third-party notices"
	echo
	echo "Games built with DingoEngine include the engine and the following third-party software."
	echo "Each component's licence follows the table. Generated by \`scripts/gather-notices.sh\`;"
	echo "edit \`scripts/notices/components.txt\`, not this file."
	echo
	echo "| Component | Licence | Used for |"
	echo "|---|---|---|"
	while IFS= read -r line; do
		echo "| [$(field "$line" 1)]($(field "$line" 2)) | $(field "$line" 3) | $(field "$line" 4) |"
	done < "$components"
	while IFS= read -r line; do
		echo
		echo "## $(field "$line" 1)"
		echo
		echo "$(field "$line" 2)"
		echo
		echo '```text'
		licence_text "$(field "$line" 5)" | tr -d '\r' | awk '{ sub(/[ \t]+$/, "") } 1'
		echo '```'
	done < "$components"
}

generate > "$tmp"

if [ "$check" = 1 ]; then
	if ! cmp -s "$tmp" "$out"; then
		echo "gather-notices: $out is out of date; run scripts/gather-notices.sh" >&2
		exit 1
	fi
	exit 0
fi
cp "$tmp" "$out"
echo "gather-notices: wrote $out"
